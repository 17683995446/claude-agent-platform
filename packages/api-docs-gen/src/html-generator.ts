/**
 * HTML Generator Module
 * Generates HTML documentation from the documentation model.
 */

import type { ModuleDoc, ClassDoc, InterfaceDoc, FunctionDoc, MethodDoc } from './doc-model.js';
import type { DocModel } from './doc-model.js';

export interface HTMLOptions {
  title?: string;
  theme?: 'light' | 'dark' | 'auto';
  includeSearch?: boolean;
  baseUrl?: string;
}

export interface SearchEntry {
  title: string;
  type: string;
  module: string;
  content: string;
  url: string;
}

export class HTMLGenerator {
  private options: HTMLOptions;

  constructor(options: HTMLOptions = {}) {
    this.options = {
      title: options.title ?? 'API Documentation',
      theme: options.theme ?? 'light',
      includeSearch: options.includeSearch ?? true,
      baseUrl: options.baseUrl ?? '',
    };
  }

  /**
   * Generate an HTML page for a documentation item.
   */
  generatePage(doc: ModuleDoc | ClassDoc | InterfaceDoc | FunctionDoc, options?: HTMLOptions): string {
    const opts = { ...this.options, ...options };
    const title = this.getDocTitle(doc);
    const content = this.renderDocContent(doc);

    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title} - ${opts.title}</title>
  <style>${this.getStyles(opts.theme)}</style>
</head>
<body>
  <header>
    <h1>${opts.title}</h1>
    <nav><a href="${opts.baseUrl}/">Home</a></nav>
  </header>
  <main>
    ${content}
  </main>
  <footer>
    <p>Generated by @claude-agent/api-docs-gen</p>
  </footer>
</body>
</html>`;
  }

  /**
   * Generate index page listing all modules.
   */
  generateIndex(modules: ModuleDoc[]): string {
    const moduleList = modules.map((mod) => {
      const items: string[] = [];
      for (const cls of mod.classes) {
        items.push(`<li><a href="${mod.name}.html#class-${cls.name}">${cls.name}</a> - Class</li>`);
      }
      for (const iface of mod.interfaces) {
        items.push(`<li><a href="${mod.name}.html#interface-${iface.name}">${iface.name}</a> - Interface</li>`);
      }
      for (const fn of mod.functions) {
        items.push(`<li><a href="${mod.name}.html#function-${fn.name}">${fn.name}()</a> - Function</li>`);
      }
      return `<div class="module">
  <h2><a href="${mod.name}.html">${mod.name}</a></h2>
  <p>${mod.description || 'No description'}</p>
  <ul>${items.join('\n    ')}</ul>
</div>`;
    }).join('\n');

    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${this.options.title}</title>
  <style>${this.getStyles(this.options.theme)}</style>
</head>
<body>
  <header>
    <h1>${this.options.title}</h1>
  </header>
  <main>
    <div class="module-list">
      ${moduleList}
    </div>
  </main>
  <footer>
    <p>Generated by @claude-agent/api-docs-gen</p>
  </footer>
</body>
</html>`;
  }

  /**
   * Generate search index data.
   */
  generateSearchIndex(modules: ModuleDoc[]): SearchEntry[] {
    const entries: SearchEntry[] = [];

    for (const mod of modules) {
      entries.push({
        title: mod.name,
        type: 'module',
        module: mod.name,
        content: mod.description,
        url: `${mod.name}.html`,
      });

      for (const cls of mod.classes) {
        entries.push({
          title: cls.name,
          type: 'class',
          module: mod.name,
          content: cls.description,
          url: `${mod.name}.html#class-${cls.name}`,
        });
        for (const method of cls.methods) {
          entries.push({
            title: `${cls.name}.${method.name}()`,
            type: 'method',
            module: mod.name,
            content: method.description,
            url: `${mod.name}.html#method-${cls.name}-${method.name}`,
          });
        }
      }

      for (const iface of mod.interfaces) {
        entries.push({
          title: iface.name,
          type: 'interface',
          module: mod.name,
          content: iface.description,
          url: `${mod.name}.html#interface-${iface.name}`,
        });
      }

      for (const fn of mod.functions) {
        entries.push({
          title: `${fn.name}()`,
          type: 'function',
          module: mod.name,
          content: fn.description,
          url: `${mod.name}.html#function-${fn.name}`,
        });
      }
    }

    return entries;
  }

  /**
   * Generate complete HTML documentation.
   */
  generateAll(docModel: DocModel, options?: HTMLOptions): Map<string, string> {
    const opts = { ...this.options, ...options };
    const output = new Map<string, string>();
    const modules = docModel.getAllModules();

    output.set('index.html', this.generateIndex(modules));

    if (opts.includeSearch) {
      const searchEntries = this.generateSearchIndex(modules);
      output.set('search.json', JSON.stringify(searchEntries, null, 2));
    }

    for (const mod of modules) {
      output.set(`${mod.name}.html`, this.generatePage(mod, opts));
    }

    return output;
  }

  // --- Internal helpers ---

  private getDocTitle(doc: ModuleDoc | ClassDoc | InterfaceDoc | FunctionDoc): string {
    if ('classes' in doc) return doc.name;
    if ('properties' in doc && 'methods' in doc && 'moduleName' in doc) {
      if ('extends' in doc && 'implements' in doc) return `Class: ${doc.name}`;
      return `Interface: ${doc.name}`;
    }
    if ('parameters' in doc && 'returnType' in doc && 'moduleName' in doc) {
      return `Function: ${doc.name}`;
    }
    return 'Documentation';
  }

  private renderDocContent(doc: ModuleDoc | ClassDoc | InterfaceDoc | FunctionDoc): string {
    if ('classes' in doc) {
      return this.renderModule(doc as ModuleDoc);
    }
    if ('properties' in doc && 'methods' in doc && 'moduleName' in doc) {
      const d = doc as ClassDoc | InterfaceDoc;
      const isClass = 'extends' in d && 'implements' in d;
      if (isClass) return this.renderClass(d as ClassDoc);
      return this.renderInterface(d as InterfaceDoc);
    }
    if ('parameters' in doc && 'returnType' in doc && 'moduleName' in doc) {
      return this.renderFunction(doc as FunctionDoc);
    }
    return '<p>Documentation content</p>';
  }

  private renderModule(mod: ModuleDoc): string {
    const sections: string[] = [];
    sections.push(`<h1>${mod.name}</h1>`);
    sections.push(`<p>${mod.description || 'No description available.'}</p>`);

    if (mod.classes.length > 0) {
      sections.push('<h2>Classes</h2>');
      for (const cls of mod.classes) {
        sections.push(`<div class="doc-item" id="class-${cls.name}">`);
        sections.push(`<h3>${cls.name}</h3>`);
        sections.push(`<p>${cls.description || ''}</p>`);
        sections.push(`<pre><code>class ${cls.name}${cls.typeParameters.length > 0 ? `<${cls.typeParameters.join(', ')}>` : ''}${cls.extends ? ` extends ${cls.extends}` : ''}</code></pre>`);
        sections.push('</div>');
      }
    }

    if (mod.interfaces.length > 0) {
      sections.push('<h2>Interfaces</h2>');
      for (const iface of mod.interfaces) {
        sections.push(`<div class="doc-item" id="interface-${iface.name}">`);
        sections.push(`<h3>${iface.name}</h3>`);
        sections.push(`<p>${iface.description || ''}</p>`);
        sections.push('</div>');
      }
    }

    if (mod.functions.length > 0) {
      sections.push('<h2>Functions</h2>');
      for (const fn of mod.functions) {
        sections.push(`<div class="doc-item" id="function-${fn.name}">`);
        sections.push(`<h3>${fn.name}()</h3>`);
        sections.push(`<p>${fn.description || ''}</p>`);
        sections.push('</div>');
      }
    }

    return sections.join('\n');
  }

  private renderClass(cls: ClassDoc): string {
    const sections: string[] = [];
    sections.push(`<h1>Class: ${cls.name}</h1>`);
    sections.push(`<p>${cls.description || ''}</p>`);

    if (cls.properties.length > 0) {
      sections.push('<h2>Properties</h2>');
      sections.push('<table><thead><tr><th>Name</th><th>Type</th><th>Description</th></tr></thead><tbody>');
      for (const prop of cls.properties) {
        sections.push(`<tr><td><code>${prop.name}</code></td><td><code>${prop.type}</code></td><td>${prop.description || '-'}</td></tr>`);
      }
      sections.push('</tbody></table>');
    }

    if (cls.methods.length > 0) {
      sections.push('<h2>Methods</h2>');
      for (const method of cls.methods) {
        sections.push(this.renderMethod(method));
      }
    }

    return sections.join('\n');
  }

  private renderMethod(method: MethodDoc): string {
    const params = method.parameters.map((p) => `${p.name}: ${p.type}`).join(', ');
    return `<div class="doc-item" id="method-${method.className}-${method.name}">
  <h3>${method.name}(${params}): ${method.returnType}</h3>
  <p>${method.description || ''}</p>
</div>`;
  }

  private renderInterface(iface: InterfaceDoc): string {
    const sections: string[] = [];
    sections.push(`<h1>Interface: ${iface.name}</h1>`);
    sections.push(`<p>${iface.description || ''}</p>`);

    if (iface.properties.length > 0) {
      sections.push('<h2>Properties</h2>');
      sections.push('<table><thead><tr><th>Name</th><th>Type</th></tr></thead><tbody>');
      for (const prop of iface.properties) {
        sections.push(`<tr><td><code>${prop.name}</code></td><td><code>${prop.type}</code></td></tr>`);
      }
      sections.push('</tbody></table>');
    }

    return sections.join('\n');
  }

  private renderFunction(fn: FunctionDoc): string {
    const params = fn.parameters.map((p) => `${p.name}: ${p.type}`).join(', ');
    return `<h1>Function: ${fn.name}</h1>
<p>${fn.description || ''}</p>
<pre><code>${fn.isAsync ? 'async ' : ''}function ${fn.name}(${params}): ${fn.returnType}</code></pre>`;
  }

  private getStyles(theme: string): string {
    const isDark = theme === 'dark';
    const bg = isDark ? '#1e1e1e' : '#ffffff';
    const fg = isDark ? '#d4d4d4' : '#333333';
    const accent = isDark ? '#569cd6' : '#0066cc';
    const codeBg = isDark ? '#2d2d2d' : '#f5f5f5';
    const border = isDark ? '#404040' : '#e0e0e0';

    return `body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; background: ${bg}; color: ${fg}; line-height: 1.6; margin: 0; padding: 2rem; }
header { border-bottom: 2px solid ${border}; padding-bottom: 1rem; margin-bottom: 2rem; }
h1 { color: ${accent}; } h2 { color: ${accent}; } h3 { color: ${fg}; }
a { color: ${accent}; text-decoration: none; } a:hover { text-decoration: underline; }
code { background: ${codeBg}; padding: 0.2rem 0.4rem; border-radius: 3px; font-family: 'Fira Code', monospace; }
pre { background: ${codeBg}; padding: 1rem; border-radius: 5px; overflow-x: auto; }
pre code { padding: 0; background: none; }
table { border-collapse: collapse; width: 100%; margin: 1rem 0; }
th, td { border: 1px solid ${border}; padding: 0.5rem 1rem; text-align: left; }
th { background: ${codeBg}; }
.doc-item { margin: 1.5rem 0; padding: 1rem; border: 1px solid ${border}; border-radius: 5px; }
.module { margin: 2rem 0; padding: 1rem; border: 1px solid ${border}; border-radius: 5px; }
footer { margin-top: 3rem; padding-top: 1rem; border-top: 1px solid ${border}; color: #888; font-size: 0.9rem; }`;
  }
}
